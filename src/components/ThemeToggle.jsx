function ThemeToggle({ preference, onCycle }) {
  const Icon = ICONS[preference] || AutoIcon;
  return (
    <button
      type="button"
      className="theme-toggle"
      onClick={onCycle}
      title={LABELS[preference]}
      aria-label={LABELS[preference]}
    >
      <Icon />
    </button>
  );
}

export default ThemeToggle;
